import { useEffect, useRef, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { ArrowRight, Check, FlaskConical, LockKeyhole, RefreshCw } from 'lucide-react';
import { assets, symbolSchema, type Symbol } from '@investing-hub/shared/contracts';
import type {
  FutureAnalysis as Analysis,
  NumericForecast,
  ExperimentalForecast,
  ForecastMode,
  ReviewContent,
} from '@investing-hub/shared/future-analysis';
import { requestFutureReview, useFutureAnalysis, useMarkets } from '../lib/api';
import { Coin, ErrorState, Notice, Skeleton } from '../components/ui';
import { money, percent, utc } from '../lib/format';

